function id(offset) {
  return domain.uuidV7FromParts(
    1_703_000_000_000 + offset,
    Uint8Array.from(Array.from({ length: 10 }, (_, index) => (offset + index + 1) & 0xff)),
  );
}

function ids(start = 100) {
  let offset = start;
  return { nextId: () => id(offset++) };
}

