  assert.deepEqual(timeline(invalid.outbox, invalid.alpha, invalid.sessionId).slice(-1).map((record) => record.event.event_type), ["turn.committed"]);
  assert.equal(invalid.driver.getMetrics(invalid.alpha, invalid.sessionId).fast_lane_failures, 1);
