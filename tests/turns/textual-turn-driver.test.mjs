test("interruption fences a resolved Fast Lane before its Presenter commit, is idempotent, and updates recovery state", async () => {
  const controlled = controlledFastLane();
  const value = await fixture({ fastLane: controlled.port });
  const pending = value.driver.submitTurn(
    value.alpha,
    value.sessionId,
    submitInput("Please stop", "client-interrupt-turn"),
    "idempotency-interrupt-turn",
    trace,
  );
  const request = await controlled.waitForRequest();
  controlled.release();
  const firstInterruption = value.driver.interruptTurn(
    value.alpha,
    value.sessionId,
    interruptionInput(request.request.generation_id, "client-interrupt-0001"),
    "idempotency-interrupt-0001",
    trace,
  );
  const replayInterruption = value.driver.interruptTurn(
    value.alpha,
    value.sessionId,
    interruptionInput(request.request.generation_id, "client-interrupt-0001"),
    "idempotency-interrupt-0001",
    trace,
  );
  const [interrupted, replayed] = await Promise.all([firstInterruption, replayInterruption]);
  assert.deepEqual(replayed, interrupted);
  assert.equal(interrupted.cancellation_status, "cancelled");
  await assert.rejects(pending, turns.TurnDriverGenerationCancelledError);
  const events = timeline(value.outbox, value.alpha, value.sessionId);
  assert.deepEqual(events.slice(-2).map((record) => record.event.event_type), ["turn.committed", "turn.interrupted"]);
  assert.equal(events.filter((record) => record.event.event_type === "turn.interrupted").length, 1);
  assert.equal(events.some((record) => record.event.event_type === "turn.committed"
    && JSON.parse(record.event.payload_json).speaker_role === "presenter"), false);
  const actor = await value.actors.getActor(value.alpha, value.sessionId);
  assert.equal((await actor.getState(value.alpha)).conversation.repair_state, "recovering_interruption");
  assert.equal(value.driver.getMetrics(value.alpha, value.sessionId).interruptions_committed, 1);
  assert.equal(value.driver.getMetrics(value.alpha, value.sessionId).generations_cancelled, 1);
});

