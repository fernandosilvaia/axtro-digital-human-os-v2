  const pending = value.driver.submitTurn(
    value.alpha,
    value.sessionId,
    submitInput("Cancel this request", "client-request-cancel"),
    "idempotency-request-can",
    trace,
    {
      assertActive() {},
      signal: requestController.signal,
    },
  );
  const fastLaneRequest = await controlled.waitForRequest();
