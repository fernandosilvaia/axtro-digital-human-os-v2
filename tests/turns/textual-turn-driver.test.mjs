function manualTimers() {
  let nextId = 0;
  const callbacks = new Map();
  return {
    scheduler: {
      setTimeout(callback, delayMs) {
        const timerId = nextId += 1;
        callbacks.set(timerId, { callback, delayMs });
        return timerId;
      },
      clearTimeout(timerId) {
        callbacks.delete(timerId);
      },
    },
    fireAll() {
      const pending = [...callbacks.values()];
      callbacks.clear();
      for (const timer of pending) timer.callback();
    },
    count() {
      return callbacks.size;
    },
  };
}

function controlledFastLane() {
  const requests = [];
  const pending = [];
  let resolveRequested;
  const requested = new Promise((resolve) => { resolveRequested = resolve; });
  return {
    port: {
      async respond(request, control) {
        requests.push({ request, control });
        resolveRequested();
        return new Promise((resolve) => pending.push({ resolve }));
      },
    },
    async waitForRequest() {
      await requested;
      assert.equal(requests.length, 1);
      return requests[0];
    },
    release(response = deterministicResponse()) {
      const current = pending.shift();
      assert.ok(current);
      current.resolve(response);
    },
  };
}

