function submitInput(text, clientTurnId, speakerParticipantId = participantAlpha) {
  return {
    schema_version: "2.0.0",
    speaker_participant_id: speakerParticipantId,
    text,
    language: "en-US",
    client_turn_id: clientTurnId,
  };
}

function interruptionInput(generationId, clientInterruptId) {
  return {
    speaker_participant_id: participantAlpha,
    generation_id: generationId,
    client_interrupt_id: clientInterruptId,
  };
}

function timeline(outbox, request, sessionId) {
  return outbox.listOutbox(request)
    .filter((record) => record.aggregate_id === sessionId)
    .sort((left, right) => left.aggregate_version - right.aggregate_version);
}

async function changePresenter({ outbox, actors, alpha, sessionId }, presenterId, eventId = id(700)) {
  const state = outbox.readInteractionAggregate(alpha, sessionId);
  assert.ok(state);
  const event = {
    schema_version: "2.0.0",
    event_id: eventId,
    event_type: "presenter.changed",
    event_version: 1,
    aggregate_type: "interaction_session",
    aggregate_id: sessionId,
    aggregate_version: state.session.state_version + 1,
    tenant_id: tenantAlpha,
    session_id: sessionId,
    producer: "tests.turn-driver",
    trace_id: trace.trace_id,
    correlation_id: trace.correlation_id,
    causation_id: timeline(outbox, alpha, sessionId).at(-1).event_id,
    data_classification: "internal",
    occurred_at: "2026-07-14T12:00:00.000Z",
    payload: {
      expected_presenter_id: presenterAlpha,
      presenter_id: presenterId,
    },
  };
  const committed = await outbox.commitInteractionEvent(alpha, event);
  const actor = await actors.getActor(alpha, sessionId);
  await actor.applyCanonicalEvent(alpha, committed.outbox.event);
}

